/**
 * Manages reservation offers generated by completed lottery draws.
 *
 * Retrieves entrant statuses, processes declined offers, promotes
 * eligible backups, and maintains consistent Firestore draw results.
 *
 * @param firestore Firestore instance used for database operations.
 * @param functions Callable endpoints for verified offer changes.
 */
class ReservationOfferModel(
    private val firestore: FirebaseFirestore = Firebase.firestore,
    private val functions: FirebaseFunctions = FirebaseFunctions.getInstance()
) {
    private val waitingList = firestore.collection("waitingList")

    /**
     * Loads the selected campsite's usable period and booked stays for a winner.
     *
     * The callable verifies the winner before returning only date-range data, so
     * other entrants' reservation details are never exposed to the client.
     *
     * @param lotteryId Lottery that produced the winning offer.
     * @param campsiteId Campsite whose dates are being displayed.
     * @param onSuccess Receives the current availability projection.
     * @param onError Receives a user-visible failure message.
     */
    fun getBookingAvailability(
        lotteryId: String,
        campsiteId: String,
        onSuccess: (LotteryBookingAvailability) -> Unit,
        onError: (String) -> Unit
    ) {
        if (lotteryId.isBlank() || campsiteId.isBlank()) {
            onError("Lottery or campsite ID is missing.")
            return
        }

        functions.getHttpsCallable("listLotteryBookingAvailability")
            .call(mapOf("lotteryId" to lotteryId, "campsiteId" to campsiteId))
            .addOnSuccessListener { response ->
                try {
                    val data = response.data as Map<*, *>
                    val bookingStart = (data["bookingStart"] as? Number)?.toLong()
                        ?: error("Availability start is missing.")
                    val bookingEnd = (data["bookingEnd"] as? Number)?.toLong()
                        ?: error("Availability end is missing.")
                    val bookedPeriods = (data["bookedPeriods"] as? List<*>)
                        .orEmpty()
                        .mapNotNull { value ->
                            val period = value as? Map<*, *> ?: return@mapNotNull null
                            val start = (period["start"] as? Number)?.toLong()
                            val end = (period["end"] as? Number)?.toLong()
                            if (start != null && end != null && start < end) {
                                BookedReservationPeriod(start, end)
                            } else {
                                null
                            }
                        }
                    onSuccess(LotteryBookingAvailability(bookingStart, bookingEnd, bookedPeriods))
                } catch (exception: Exception) {
                    onError(exception.message ?: "Could not read campsite availability.")
                }
            }
            .addOnFailureListener { error ->
                onError(error.message ?: "Could not read campsite availability.")
            }
    }

    /**
     * Listens for reservation confirmations that change a lottery's availability.
     *
     * @param lotteryId Lottery whose availability version is observed.
     * @param onChanged Invoked when Firebase reports an availability change.
     * @param onError Receives listener failures.
     * @return A registration that callers must remove when the screen closes.
     */
    fun listenForBookingAvailabilityChanges(
        lotteryId: String,
        onChanged: () -> Unit,
        onError: (String) -> Unit
    ): ListenerRegistration? {
        if (lotteryId.isBlank()) {
            onError("Lottery ID is missing.")
            return null
        }

        return firestore.collection("lottery").document(lotteryId)
            .addSnapshotListener { _, exception ->
                if (exception == null) {
                    onChanged()
                } else {
                    onError(exception.message ?: "Could not watch campsite availability.")
                }
            }
    }

    // Hiral - [AI-08] OpenAI ChatGPT Implement US-02.04.02
    /**
     * Checks availability or confirms the winner's chosen campsite and stay.
     *
     * @param checkOnly Whether to check the dates without reserving them.
     */
    fun checkOrConfirmBooking(
        lotteryId: String,
        campsiteId: String,
        start: Long,
        end: Long,
        checkOnly: Boolean,
        onSuccess: () -> Unit,
        onError: (String) -> Unit
    ) {
        functions.getHttpsCallable("confirmLotteryBooking")
            .call(
                mapOf(
                    "lotteryId" to lotteryId,
                    "campsiteId" to campsiteId,
                    "start" to start,
                    "end" to end,
                    "checkOnly" to checkOnly
                )
            )
            .addOnSuccessListener { onSuccess() }
            .addOnFailureListener { onError(it.message ?: "Could not check the booking.") }
    }

    /**
     * Retrieves the entrant's current lottery draw status from Firestore.
     *
     * Returns null when no registration exists and defaults to WAITING
     * when the registration has no recorded draw status.
     *
     * @param lotteryId Unique identifier of the lottery.
     * @param accountId Unique identifier of the entrant's account.
     * @param onResult Callback receiving the entrant's status or null.
     * @param onError Callback receiving an error message.
     */
    fun getEntrantDrawStatus(
        lotteryId: String,
        accountId: String,
        onResult: (String?) -> Unit,
        onError: (String) -> Unit
    ) {
        if (lotteryId.isBlank() || accountId.isBlank()) {
            onError("Lottery or account ID is missing")
            return
        }

        val registrationId = "${lotteryId}_${accountId}"

        waitingList.document(registrationId)
            .get(Source.SERVER)
            .addOnSuccessListener { document ->
                if (!document.exists()) {
                    onResult(null)
                    return@addOnSuccessListener
                }

                if (document.getString("lotteryId") != lotteryId ||
                    document.getString("accountId") != accountId
                ) {
                    onError("Registration information is invalid")
                    return@addOnSuccessListener
                }

                val status = document.getString("drawStatus")
                    ?: "WAITING"

                onResult(status)
            }
            .addOnFailureListener { exception ->
                onError(
                    exception.message ?: "Failed to load lottery result"
                )
            }
    }


    /**
     * Declines a winning reservation opportunity and promotes the next
     * eligible backup when one is available.
     *
     * Checks for an existing non-cancelled reservation for the same
     * entrant and campsite before starting the decline transaction.
     *
     * @param lotteryId Unique identifier of the lottery.
     * @param accountId Account ID of the declining entrant.
     * @param onSuccess Callback invoked after a successful transaction.
     * @param onError Callback receiving a validation or transaction error.
     */
    fun declineReservationOffer(
        lotteryId: String,
        accountId: String,
        onSuccess: () -> Unit,
        onError: (String) -> Unit
    ) {
        functions.getHttpsCallable("declineLotteryOffer")
            .call(mapOf("lotteryId" to lotteryId, "accountId" to accountId))
            .addOnSuccessListener { onSuccess() }
            .addOnFailureListener { error -> onError(error.message ?: "Could not decline the offer.") }
    }

    /**
     * Retrieves the account IDs of entrants who declined winning offers.
     *
     * Returns an empty list when no draw result or declined list exists.
     *
     * @param lotteryId Unique identifier of the lottery.
     * @param onSuccess Callback receiving the declined entrant IDs.
     * @param onError Callback receiving an error message.
     */
    fun getDeclinedEntrants(
        lotteryId: String,
        onSuccess: (List<String>) -> Unit,
        onError: (String) -> Unit
    ) {
        if (lotteryId.isBlank() || lotteryId.contains("/")) {
            onError("Invalid lottery ID")
            return
        }

        firestore.collection("lotteryDrawResults")
            .document(lotteryId)
            .get(Source.SERVER)
            .addOnSuccessListener { document ->
                if (!document.exists()) {
                    onSuccess(emptyList())
                    return@addOnSuccessListener
                }

                val declinedIds = document.get("declinedIds") as? List<*>

                if (declinedIds == null) {
                    onSuccess(emptyList())
                } else {
                    onSuccess(declinedIds.filterIsInstance<String>())
                }
            }
            .addOnFailureListener { exception ->
                onError(
                    exception.message ?: "Failed to load declined entrants"
                )
            }
    }

}
